"""Verified row-preserving embedding caches. Loading never downloads a model.

Legacy .npy files have no authenticated text mapping and fail closed here.
The separately labeled historical pilot can inspect them conditionally; it
must never manufacture a 'verified' generation manifest for those files.
"""
from collections import defaultdict
import hashlib
from importlib.metadata import version
import json
import os
from pathlib import Path
import tempfile
import numpy as np

SCHEMA = 1
PREPROCESSING = 'response-v1: ERROR/blank -> empty; other text unchanged'


class CacheIntegrityError(ValueError):
    pass


def sha256(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
                                     separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def response_valid(record):
    text = record.get('response')
    return isinstance(text, str) and bool(text.strip()) and not text.lstrip().startswith('ERROR:')


def embedding_text(record):
    return record['response'] if response_valid(record) else ''


def row_receipts(records):
    return [dict(record_sha256=digest(r), text_sha256=digest(embedding_text(r)),
                 valid=response_valid(r)) for r in records]


def manifest_path(path):
    return Path(path).with_suffix('.manifest.json')


def _validate_array(arr, count):
    if (arr.ndim != 2 or arr.shape[0] != count or arr.shape[1] == 0 or
        not np.issubdtype(arr.dtype, np.number) or not np.isfinite(arr).all()):
        raise CacheIntegrityError('Embedding shape, row count, or finite-number check failed')


def save_cache(path, arr, records, encoder, source_file):
    """Call ONLY for arrays just generated from these records, in this order.

    Hashes detect staleness/corruption after creation; they cannot establish
    honesty of the producer or retroactively authenticate historical arrays.
    """
    path = Path(path)
    arr = np.asarray(arr)
    _validate_array(arr, len(records))
    if not encoder.get('model_name') or not encoder.get('artifact_sha256'):
        raise CacheIntegrityError('Encoder name and immutable artifact fingerprint required')
    source_file = Path(source_file)
    actual = read_records(source_file)
    if row_receipts(actual) != row_receipts(records):
        raise CacheIntegrityError('Source JSONL differs from rows passed to encoder')
    path.parent.mkdir(parents=True, exist_ok=True)
    # Each file replaces atomically. A crash between replacements yields a hash
    # mismatch, never an apparently valid partially updated cache.
    with tempfile.NamedTemporaryFile(dir=path.parent, suffix='.npy', delete=False) as f:
        temporary = Path(f.name)
        np.save(f, arr, allow_pickle=False)
    try:
        manifest = dict(schema=SCHEMA, provenance='generated_with_row_receipts',
                        preprocessing=PREPROCESSING, encoder=encoder,
                        source_file=os.path.relpath(source_file.resolve(), path.parent.resolve()),
                        source_sha256=sha256(source_file), rows=row_receipts(records),
                        shape=list(arr.shape), dtype=str(arr.dtype), array_sha256=sha256(temporary))
        os.replace(temporary, path)
        with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, suffix='.json',
                                         encoding='utf-8', delete=False) as f:
            temporary_manifest = Path(f.name)
            json.dump(manifest, f, indent=2, allow_nan=False)
            f.write('\n')
        os.replace(temporary_manifest, manifest_path(path))
    finally:
        temporary.unlink(missing_ok=True)


def read_records(path):
    return [json.loads(l) for l in Path(path).read_text(encoding='utf-8-sig').splitlines() if l.strip()]


def load_cache(path, records=None, model_name=None):
    path = Path(path)
    try:
        manifest = json.loads(manifest_path(path).read_text())
        if (manifest['schema'] != SCHEMA or manifest['preprocessing'] != PREPROCESSING or
            manifest['provenance'] != 'generated_with_row_receipts'):
            raise CacheIntegrityError('Unsupported or unverified cache provenance')
        encoder = manifest['encoder']
        if not encoder.get('model_name') or not encoder.get('artifact_sha256'):
            raise CacheIntegrityError('Missing encoder fingerprint')
        if model_name is not None and model_name != encoder['model_name']:
            raise CacheIntegrityError('Cache was generated by a different encoder')
        source = path.parent / manifest['source_file']
        if sha256(source) != manifest['source_sha256']:
            raise CacheIntegrityError('Raw JSONL changed since embedding')
        source_records = read_records(source)
        receipts = row_receipts(source_records)
        if receipts != manifest['rows'] or (records is not None and row_receipts(records) != receipts):
            raise CacheIntegrityError('Embedding row text/order/metadata changed')
        if sha256(path) != manifest['array_sha256']:
            raise CacheIntegrityError('Embedding array hash mismatch')
        arr = np.load(path, allow_pickle=False)
        _validate_array(arr, len(receipts))
        if list(arr.shape) != manifest['shape'] or str(arr.dtype) != manifest['dtype']:
            raise CacheIntegrityError('Embedding shape/dtype manifest mismatch')
        return arr
    except (OSError, KeyError, TypeError, json.JSONDecodeError) as exc:
        raise CacheIntegrityError(f'Unverified or unreadable cache {path.name}: {exc}. '
                                  'No model was loaded. Re-embed explicitly with an installed encoder.') from exc


def fingerprint_encoder(model, model_name):
    """Fingerprint loaded weights, module configuration, tokenizer and runtime."""
    h = hashlib.sha256()
    for key, tensor in sorted(model.state_dict().items()):
        h.update(key.encode())
        value = tensor.detach().cpu().contiguous()
        h.update(str(value.dtype).encode())
        h.update(str(tuple(value.shape)).encode())
        # Byte view also supports bfloat16, which numpy cannot represent directly.
        h.update(value.view(__import__('torch').uint8).numpy().tobytes())
    config = {name: module.get_config_dict() if hasattr(module, 'get_config_dict') else repr(module)
              for name, module in model._modules.items()}
    tokenizer = model.tokenizer
    config['tokenizer'] = tokenizer.backend_tokenizer.to_str() if hasattr(tokenizer, 'backend_tokenizer') else tokenizer.get_vocab()
    config['tokenizer_special_tokens'] = {k: str(v) for k, v in tokenizer.special_tokens_map.items()}
    config['max_seq_length'] = model.max_seq_length
    config['prompts'] = getattr(model, 'prompts', {})
    config['default_prompt_name'] = getattr(model, 'default_prompt_name', None)
    config['truncate_dim'] = getattr(model, 'truncate_dim', None)
    h.update(digest(config).encode())
    return dict(model_name=model_name, artifact_sha256=h.hexdigest(),
                sentence_transformers=version('sentence-transformers'),
                transformers=version('transformers'), torch=version('torch'))


def compute_verified_embeddings(data, embed_dir, raw_dir, model_name, force=False, prefix=''):
    """Use verified caches or an already installed encoder; never fetch weights.

    Errors/blank generations stay in disk receipts to preserve row alignment,
    but are excluded from the numerical arrays returned to experiment metrics.
    """
    result = defaultdict(dict)
    pending = []
    encoder_identity = None
    for pid, temperatures in data.items():
        for temp, records in temperatures.items():
            path = Path(embed_dir) / f'{prefix}{pid}_{temp}.npy'
            if path.exists() and not force:
                arr = load_cache(path, records, model_name)
                identity = json.loads(manifest_path(path).read_text())["encoder"]
                if encoder_identity is not None and identity != encoder_identity:
                    raise CacheIntegrityError("Mixed encoder artifacts/runtimes in one analysis")
                encoder_identity = identity
                mask = np.array([response_valid(r) for r in records], dtype=bool)
                if mask.any():
                    result[pid][temp] = arr[mask]
            elif records:
                pending.append((pid, temp, path, records))
    if pending:
        # Deliberately lazy: a cache-only run never imports ML/model runtimes.
        try:
            from sentence_transformers import SentenceTransformer
            model = SentenceTransformer(model_name, local_files_only=True)
        except (ImportError, OSError) as exc:
            raise RuntimeError('A locally installed embedding model is required. '
                               'Stopped without downloading weights.') from exc
        encoder = fingerprint_encoder(model, model_name)
        if encoder_identity is not None and encoder != encoder_identity:
            raise CacheIntegrityError("Installed encoder differs from existing caches; explicitly regenerate all cells")
        for pid, temp, path, records in pending:
            arr = np.asarray(model.encode([embedding_text(r) for r in records],
                                          show_progress_bar=False, batch_size=128))
            save_cache(path, arr, records, encoder, Path(raw_dir) / f'{pid}_{temp}.jsonl')
            mask = np.array([response_valid(r) for r in records], dtype=bool)
            if mask.any():
                result[pid][temp] = arr[mask]
    return result
