class UncertaintyType(Enum):
    WIDENING = "widening"           # belief is losing certainty over time
    SPARSE = "sparse"               # low evidence count, not enough data
    CONFLICTED = "conflicted"       # held contradiction, Belnap BOTH
    CONVERGING = "converging"       # two beliefs heading toward collision
    TOPOLOGICAL_HOLE = "hole"       # gap in belief coverage
    GAP_GROWING = "gap_growing"     # belief/speech gap widening
    STALE = "stale"                 # belief hasn't been updated in a long time
    HIGH_FISHER = "high_fisher"     # high Fisher distance to related beliefs (outlier)


class Urgency(Enum):
    LOW = "low"           # interesting but not pressing
    MEDIUM = "medium"     # should address in next few interactions
    HIGH = "high"         # address soon -- belief state degrading
    CRITICAL = "critical" # address now -- collision imminent or coherence at risk


