@dataclass
class Inquiry:
    """A request for information that would reduce epistemic uncertainty.

    This is what the active inference loop produces: not just
    'I don't know X' but 'here's what I'd ask to reduce my
    uncertainty about X, here's why, and here's how urgent it is.'
    """
    inquiry_id: str
    uncertainty_type: UncertaintyType
    urgency: Urgency
    target_beliefs: List[str]       # belief IDs involved
    question: str                   # natural language question to ask
    expected_info_gain: float       # estimated reduction in uncertainty (0-1)
    rationale: str                  # why this inquiry matters
    created_at: float = 0.0
    resolved: bool = False
    resolved_at: float = 0.0
    resolution_reduced_uncertainty: Optional[float] = None  # actual gain after resolution

    def __post_init__(self):
        if self.created_at == 0.0:
            self.created_at = time.time()


# ---------------------------------------------------------------------------
# Free energy computation (simplified for belief splats)
# ---------------------------------------------------------------------------

def compute_belief_free_energy(splat: MemorySplat) -> float:
    """Compute a simplified free energy score for a single belief.

    Free energy ~ uncertainty + complexity

    For a Gaussian splat:
      - Uncertainty = total covariance (how wide the splat is)
      - Complexity = deviation from prior (how far from default)
      - Confidence penalty = low alpha means less trusted

    Higher free energy = more uncertain = more value in seeking info.
    """
    # Uncertainty: log-sum of covariance (entropy proxy)
    # For diagonal Gaussian: entropy ~ 0.5 * sum(log(sigma_i)) + const
    entropy = 0.5 * float(np.sum(np.log(splat.sigma + 1e-10)))

    # Confidence penalty: low confidence adds free energy
    confidence_penalty = -math.log(max(splat.alpha, 0.01))

    # Evidence sparsity: fewer updates = more uncertain
    sparsity = 1.0 / max(splat.update_count + 1, 1)

    return entropy + confidence_penalty + sparsity


def expected_information_gain(
    splat: MemorySplat,
    hypothetical_tightening: float = 0.3,
) -> float:
    """Estimate how much free energy we'd reduce by getting new evidence.

    Models the counterfactual: if we got confirming evidence that
    tightened the splat by `hypothetical_tightening`, how much
    would free energy drop?
    """
    current_fe = compute_belief_free_energy(splat)

    # Simulate tightening
    hypothetical = MemorySplat(
        "hyp", splat.mu.copy(),
        splat.sigma * (1.0 - hypothetical_tightening),
        min(1.0, splat.alpha + 0.1),
        update_count=splat.update_count + 1,
    )
    hypothetical_fe = compute_belief_free_energy(hypothetical)

    return max(0.0, current_fe - hypothetical_fe)


