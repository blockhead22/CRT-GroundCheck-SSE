class InquiryGenerator:
    """Generates clarification requests from uncertainty scans.

    This is the active inference loop: scan -> identify -> question -> track.
    """

    def __init__(self):
        self.inquiries: List[Inquiry] = []
        self._counter = 0

    def _next_id(self) -> str:
        self._counter += 1
        return f"inq_{self._counter:04d}"

    def generate_from_widening(
        self, widening: List[Tuple[MemorySplat, float]]
    ) -> List[Inquiry]:
        """Generate inquiries for beliefs losing certainty."""
        inquiries = []
        for splat, velocity in widening[:5]:  # top 5
            urgency = Urgency.HIGH if velocity > 1.0 else Urgency.MEDIUM
            eig = expected_information_gain(splat)

            inq = Inquiry(
                inquiry_id=self._next_id(),
                uncertainty_type=UncertaintyType.WIDENING,
                urgency=urgency,
                target_beliefs=[splat.memory_id],
                question=(
                    f"I've noticed my understanding of '{splat.text}' "
                    f"has become less certain over time. "
                    f"Can you help me clarify where things stand?"
                ),
                expected_info_gain=eig,
                rationale=(
                    f"Covariance velocity={velocity:.4f} (positive = widening). "
                    f"This belief is under epistemic pressure. "
                    f"New evidence could reduce uncertainty significantly."
                ),
            )
            inquiries.append(inq)
            self.inquiries.append(inq)
        return inquiries

    def generate_from_convergence(
        self, converging: List[Tuple[MemorySplat, MemorySplat, List[float]]]
    ) -> List[Inquiry]:
        """Generate inquiries for converging belief pairs (pre-contradiction)."""
        inquiries = []
        for a, b, trend in converging[:5]:
            # Estimate time to collision from trend
            if len(trend) >= 2 and trend[-1] > trend[-2]:
                growth_rate = trend[-1] - trend[-2]
                # Rough estimate: steps until overlap > 0.5
                remaining = (0.5 - trend[-1]) / max(growth_rate, 1e-6)
                urgency = Urgency.CRITICAL if remaining < 5 else Urgency.HIGH
            else:
                urgency = Urgency.MEDIUM

            inq = Inquiry(
                inquiry_id=self._next_id(),
                uncertainty_type=UncertaintyType.CONVERGING,
                urgency=urgency,
                target_beliefs=[a.memory_id, b.memory_id],
                question=(
                    f"I'm noticing a potential tension forming between "
                    f"'{a.text}' and '{b.text}'. "
                    f"These seem to be heading toward a contradiction. "
                    f"Can you help me understand how both of these are true for you?"
                ),
                expected_info_gain=0.7,  # convergence resolution is high-value
                rationale=(
                    f"Overlap trend: {[f'{t:.4f}' for t in trend[-4:]]}. "
                    f"Beliefs are converging in embedding space. "
                    f"Early intervention prevents forced resolution later."
                ),
            )
            inquiries.append(inq)
            self.inquiries.append(inq)
        return inquiries

    def generate_from_sparse(
        self, sparse: List[MemorySplat]
    ) -> List[Inquiry]:
        """Generate inquiries for under-evidenced beliefs."""
        inquiries = []
        for splat in sparse[:3]:  # top 3
            eig = expected_information_gain(splat)
            inq = Inquiry(
                inquiry_id=self._next_id(),
                uncertainty_type=UncertaintyType.SPARSE,
                urgency=Urgency.LOW,
                target_beliefs=[splat.memory_id],
                question=(
                    f"I don't have much information about '{splat.text}'. "
                    f"Is this still accurate? Any updates?"
                ),
                expected_info_gain=eig,
                rationale=(
                    f"Only {splat.update_count} evidence updates. "
                    f"Low evidence count means high prior uncertainty."
                ),
            )
            inquiries.append(inq)
            self.inquiries.append(inq)
        return inquiries

    def generate_from_stale(
        self, stale: List[Tuple[MemorySplat, float]]
    ) -> List[Inquiry]:
        """Generate inquiries for beliefs that haven't been updated."""
        inquiries = []
        for splat, age_days in stale[:3]:
            urgency = Urgency.MEDIUM if age_days > 90 else Urgency.LOW
            inq = Inquiry(
                inquiry_id=self._next_id(),
                uncertainty_type=UncertaintyType.STALE,
                urgency=urgency,
                target_beliefs=[splat.memory_id],
                question=(
                    f"It's been {age_days:.0f} days since I last confirmed "
                    f"'{splat.text}'. Is this still the case?"
                ),
                expected_info_gain=0.3,
                rationale=(
                    f"Last updated {age_days:.0f} days ago. "
                    f"World state may have changed."
                ),
            )
            inquiries.append(inq)
            self.inquiries.append(inq)
        return inquiries

    def generate_from_gap_growth(
        self, gaps: List[Tuple[str, float]]
    ) -> List[Inquiry]:
        """Generate meta-inquiries about growing belief/speech gaps."""
        inquiries = []
        for domain, growth in gaps[:3]:
            inq = Inquiry(
                inquiry_id=self._next_id(),
                uncertainty_type=UncertaintyType.GAP_GROWING,
                urgency=Urgency.HIGH,
                target_beliefs=[],
                question=(
                    f"I've been less transparent about {domain} topics recently. "
                    f"My confidence in that area has shifted. "
                    f"Should I share more of my uncertainty with you, "
                    f"or is the current level of hedging appropriate?"
                ),
                expected_info_gain=0.5,
                rationale=(
                    f"Belief/speech gap in '{domain}' grew by {growth:.3f}. "
                    f"This is the system detecting its own increasing opacity "
                    f"and asking whether to recalibrate."
                ),
            )
            inquiries.append(inq)
            self.inquiries.append(inq)
        return inquiries

    def generate_from_outliers(
        self, outliers: List[Tuple[MemorySplat, float]]
    ) -> List[Inquiry]:
        """Generate inquiries for informationally isolated beliefs."""
        inquiries = []
        for splat, distance in outliers[:3]:
            inq = Inquiry(
                inquiry_id=self._next_id(),
                uncertainty_type=UncertaintyType.HIGH_FISHER,
                urgency=Urgency.LOW,
                target_beliefs=[splat.memory_id],
                question=(
                    f"'{splat.text}' seems informationally isolated from "
                    f"your other beliefs. It's either uniquely important "
                    f"or I may have gotten something wrong. "
                    f"Does this still fit with your current thinking?"
                ),
                expected_info_gain=0.4,
                rationale=(
                    f"Fisher distance to nearest neighbors: {distance:.2f} "
                    f"(well above median). This belief doesn't integrate "
                    f"naturally with the rest of the belief space."
                ),
            )
            inquiries.append(inq)
            self.inquiries.append(inq)
        return inquiries

    def resolve(self, inquiry_id: str, uncertainty_reduced: float = 0.5):
        """Mark an inquiry as resolved after getting clarification."""
        for inq in self.inquiries:
            if inq.inquiry_id == inquiry_id:
                inq.resolved = True
                inq.resolved_at = time.time()
                inq.resolution_reduced_uncertainty = uncertainty_reduced
                return

    @property
    def open_inquiries(self) -> List[Inquiry]:
        return [i for i in self.inquiries if not i.resolved]

    @property
    def resolved_inquiries(self) -> List[Inquiry]:
        return [i for i in self.inquiries if i.resolved]

    def prioritized_queue(self) -> List[Inquiry]:
        """Return open inquiries sorted by urgency then expected gain."""
        urgency_order = {
            Urgency.CRITICAL: 0,
            Urgency.HIGH: 1,
            Urgency.MEDIUM: 2,
            Urgency.LOW: 3,
        }
        return sorted(
            self.open_inquiries,
            key=lambda i: (urgency_order[i.urgency], -i.expected_info_gain),
        )


# ---------------------------------------------------------------------------
# The active inference loop (the main integration point)
# ---------------------------------------------------------------------------

def run_active_inference_cycle(
    splats: List[MemorySplat],
    store: Optional[BeliefStore] = None,
    audit_log: Optional[GapAuditLog] = None,
    generator: Optional[InquiryGenerator] = None,
) -> InquiryGenerator:
    """Run one cycle of the active inference loop.

    Scans the belief state for all types of uncertainty,
    generates prioritized inquiries, and returns them.

    This is the heartbeat of the self-aware memory system.
    Call it periodically (e.g., at the start of each conversation,
    or after significant belief updates).
    """
    if generator is None:
        generator = InquiryGenerator()

    # --- Scan 1: Widening beliefs ---
    widening = scan_widening_beliefs(splats)
    if widening:
        generator.generate_from_widening(widening)

    # --- Scan 2: Converging pairs ---
    converging = scan_converging_pairs(splats)
    if converging:
        generator.generate_from_convergence(converging)

    # --- Scan 3: Sparse beliefs ---
    sparse = scan_sparse_beliefs(splats)
    if sparse:
        generator.generate_from_sparse(sparse)

    # --- Scan 4: Stale beliefs ---
    stale = scan_stale_beliefs(splats)
    if stale:
        generator.generate_from_stale(stale)

    # --- Scan 5: Belief/speech gaps ---
    if store and audit_log:
        gaps = scan_belief_speech_gaps(store, audit_log)
        if gaps:
            generator.generate_from_gap_growth(gaps)

    # --- Scan 6: Fisher outliers ---
    if len(splats) >= 5:
        outliers = scan_fisher_outliers(splats)
        if outliers:
            generator.generate_from_outliers(outliers)

    return generator


