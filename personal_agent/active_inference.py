def scan_widening_beliefs(
    splats: List[MemorySplat],
    velocity_threshold: float = 0.0,
) -> List[Tuple[MemorySplat, float]]:
    """Find beliefs whose covariance is growing (uncertainty increasing).

    These are beliefs under epistemic pressure -- something is
    causing the system to become less certain over time.
    """
    results = []
    for s in splats:
        vel = covariance_velocity(s)
        if vel is not None and vel > velocity_threshold:
            results.append((s, vel))
    return sorted(results, key=lambda x: -x[1])


def scan_sparse_beliefs(
    splats: List[MemorySplat],
    min_updates: int = 2,
) -> List[MemorySplat]:
    """Find beliefs with very little evidence."""
    return [s for s in splats if s.update_count < min_updates]


def scan_converging_pairs(
    splats: List[MemorySplat],
    cosine_threshold: float = 0.3,
) -> List[Tuple[MemorySplat, MemorySplat, List[float]]]:
    """Find pairs of beliefs whose overlap trend is increasing.

    These are potential future contradictions -- the foresight signal.
    """
    results = []
    for i in range(len(splats)):
        for j in range(i + 1, len(splats)):
            a, b = splats[i], splats[j]
            cos = cosine_similarity(a, b)
            if cos < cosine_threshold:
                continue  # unrelated
            trend = predict_overlap_trend(a, b, steps=3)
            if trend and len(trend) >= 3:
                # Check if overlap is growing
                recent = trend[-3:]
                if all(recent[k+1] > recent[k] for k in range(len(recent)-1)):
                    results.append((a, b, trend))
    return results


def scan_stale_beliefs(
    splats: List[MemorySplat],
    staleness_threshold_days: float = 30.0,
) -> List[Tuple[MemorySplat, float]]:
    """Find beliefs that haven't been updated in a long time.

    Stale beliefs may be outdated. The system should check
    whether they're still valid.
    """
    now = time.time()
    results = []
    for s in splats:
        age_days = (now - s.last_updated) / 86400.0
        if age_days > staleness_threshold_days:
            results.append((s, age_days))
    return sorted(results, key=lambda x: -x[1])


def scan_belief_speech_gaps(
    store: BeliefStore,
    audit_log: GapAuditLog,
    gap_threshold: float = 0.3,
) -> List[Tuple[str, float]]:
    """Find domains where the belief/speech gap is growing.

    A growing gap means the system is becoming less transparent
    in that area -- it should either recalibrate its beliefs or
    adjust its speech policy.
    """
    by_domain = audit_log.by_domain()
    results = []
    for domain, entries in by_domain.items():
        if len(entries) < 4:
            continue
        # Compare first half to second half
        mid = len(entries) // 2
        early_avg = sum(e.gap_magnitude for e in entries[:mid]) / mid
        late_avg = sum(e.gap_magnitude for e in entries[mid:]) / (len(entries) - mid)
        growth = late_avg - early_avg
        if growth > gap_threshold:
            results.append((domain, growth))
    return sorted(results, key=lambda x: -x[1])


def scan_fisher_outliers(
    splats: List[MemorySplat],
    outlier_factor: float = 2.0,
) -> List[Tuple[MemorySplat, float]]:
    """Find beliefs with unusually high Fisher distance to their neighbors.

    These are beliefs that are informationally isolated --
    they're certain about something that doesn't fit with
    the rest of the belief space. Could be uniquely important
    or could be wrong.
    """
    if len(splats) < 3:
        return []

    # Compute average Fisher distance to k nearest neighbors
    k = min(5, len(splats) - 1)
    outliers = []

    for i, s in enumerate(splats):
        distances = []
        for j, other in enumerate(splats):
            if i == j:
                continue
            distances.append(fisher_rao_distance(s, other))
        distances.sort()
        avg_knn_dist = sum(distances[:k]) / k
        outliers.append((s, avg_knn_dist))

    # Flag those with distance > outlier_factor * median
    median_dist = sorted(d for _, d in outliers)[len(outliers) // 2]
    return [(s, d) for s, d in outliers if d > outlier_factor * median_dist]


